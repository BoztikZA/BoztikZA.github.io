/* =========================================================
   SIGNED DOWNLOAD / PREVIEW

   file.delivery_id / file.file_path come straight from getPublicDelivery's
   delivery_files array — file_path holds this system's short fileId
   rather than a literal storage path (see types.ts's PublicDelivery doc
   comment on the Worker side for why that's safe).
========================================================= */

async function requestSignedUrl(file, intent) {
  if (!file?.file_path) {
    throw new Error("requestSignedUrl: file.file_path is missing — cannot request a signed URL for an unknown object.");
  }
  const deliveryId = file.delivery_id || file.deliveryId;
  if (!deliveryId) {
    throw new Error("requestSignedUrl: delivery ID is missing.");
  }

  const result = await apiFetch(
    `/api/d/${encodeURIComponent(deliveryId)}/files/${encodeURIComponent(file.file_path)}/access?intent=${intent}`,
    { method: "POST" }
  );
  return result.url;
}

export async function signedDownload(file) {
  return requestSignedUrl(file, "download");
}

export async function signedPreview(file) {
  return requestSignedUrl(file, "preview");
}

/* =========================================================
   REDDIT METADATA
   Best-effort only. Callers must treat any thrown error as
   "auto-fill unavailable" and fall back to manual entry — never
   block delivery creation on this.
========================================================= */

export async function fetchRedditMetadata(url) {
  const trimmedUrl = (url || "").trim();
  if (!trimmedUrl) {
    throw new Error("No Reddit URL supplied.");
  }

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 8000);

  let response;
  try {
    response = await fetch(apiUrl(`/api/reddit-metadata?url=${encodeURIComponent(trimmedUrl)}`), {
      signal: controller.signal
    });
  } catch (error) {
    const timedOut = error?.name === "AbortError";
    throw new Error(timedOut ? "Reddit took too long to respond." : "Could not reach the metadata service.");
  } finally {
    clearTimeout(timeout);
  }

  const result = await parseJsonSafely(response);
  if (!response.ok || !result?.title) {
    throw new Error(result?.message || "Could not read this Reddit thread's title.");
  }

  return {
    title: result.title,
    subreddit: result.subreddit || null,
    author: result.author || null,
    canonicalUrl: result.canonicalUrl || result.redditUrl || trimmedUrl,
    redditUrl: result.redditUrl || trimmedUrl
  };
}
