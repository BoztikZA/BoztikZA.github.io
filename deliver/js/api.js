/* =========================================================
   CREATE DELIVERY

   Internally a three-step exchange with the Worker (init -> direct-to-R2
   upload -> finalize, see Phase 2 §8), but that's invisible to the
   caller: the signature and behaviour match the original Supabase-backed
   createDelivery(metadata, files, onProgress) exactly, including that
   metadata.id (pre-generated by dashboard.js via shared.js's
   deliveryId()) is honoured rather than overwritten.
========================================================= */

export async function createDelivery(metadata, files, onProgress) {
  const init = await apiFetch("/admin/uploads/init", {
    method: "POST",
    body: JSON.stringify({
      deliveryId: metadata.id,
      files: files.map((f) => ({ fileName: f.name, fileSize: f.size }))
    })
  });

  for (let i = 0; i < files.length; i++) {
    const file = files[i];
    const upload = init.uploads[i];
    const putResponse = await fetch(upload.putUrl, {
      method: "PUT",
      body: file
    });
    if (!putResponse.ok) {
      throw new Error(`Upload failed for ${file.name} (HTTP ${putResponse.status}).`);
    }
    onProgress?.((i + 1) / files.length);
  }

  await apiFetch("/admin/uploads/finalize", {
    method: "POST",
    body: JSON.stringify({
      deliveryId: init.deliveryId,
      uploadIds: init.uploads.map((u) => u.uploadId),
      projectName: metadata.project_name ?? null,
      clientName: metadata.client_name ?? null,
      notes: metadata.notes ?? null,
      expiresAt: toUnixSeconds(metadata.expires_at),
      supportEnabled: metadata.support_enabled ?? true,
      isPhotoshopBattles: metadata.source_meta?.type === "photoshop_battles",
      source: metadata.source ?? null,
      sourceMeta: metadata.source_meta ?? null,
      redditSource: metadata.reddit_source ?? null
    })
  });
}

/* =========================================================
   UPDATE DELIVERY
========================================================= */

const UPDATE_FIELD_MAP = {
  project_name: "projectName",
  client_name: "clientName",
  notes: "notes",
  expires_at: "expiresAt",
  source: "source",
  source_meta: "sourceMeta",
  reddit_source: "redditSource"
};

export async function updateDelivery(deliveryId, updates = {}) {
  if (!deliveryId) throw new Error("updateDelivery: delivery ID is required.");
  if (!updates || typeof updates !== "object") {
    throw new Error("updateDelivery: updates must be an object.");
  }

  const payload = {};
  for (const [snakeKey, camelKey] of Object.entries(UPDATE_FIELD_MAP)) {
    if (Object.prototype.hasOwnProperty.call(updates, snakeKey)) {
      payload[camelKey] =
        snakeKey === "expires_at" && updates[snakeKey] != null
          ? toUnixSeconds(updates[snakeKey])
          : updates[snakeKey];
    }
  }

  if (Object.keys(payload).length === 0) {
    throw new Error("updateDelivery: no editable fields were supplied.");
  }

  await apiFetch(`/admin/deliveries/${encodeURIComponent(deliveryId)}`, {
    method: "PATCH",
    body: JSON.stringify(payload)
  });
}

