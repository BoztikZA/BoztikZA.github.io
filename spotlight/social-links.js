const escapeHtml = value => String(value ?? "").replace(/[&<>"']/g, char => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
}[char]));

export function safeSocialUrl(platform, value) {
  const definition = Object.prototype.hasOwnProperty.call(platforms, platform) ? platforms[platform] : null;
  if (!definition || typeof value !== "string" || value.length > 500) return null;
  try {
    const url = new URL(value);
    if (url.protocol !== "https:" || url.username || url.password || url.port) return null;
    const host = url.hostname.toLowerCase().replace(/\.$/, "");
    return definition.hosts.some(root => host === root || host.endsWith("." + root)) ? url.href : null;
  } catch {
    return null;
  }
}

export function socialIconSvg(platform) {
  const definition = Object.prototype.hasOwnProperty.call(platforms, platform) ? platforms[platform] : null;
  if (!definition) return "";
  const viewBox = definition.viewBox || "0 0 24 24";
  return `<svg viewBox="${viewBox}" aria-hidden="true" focusable="false"><path fill="currentColor" d="${definition.path}"></path></svg>`;
}

export function socialLinksMarkup(links, profileName, className = "sp-social-link", includeText = false) {
  if (!links || typeof links !== "object" || Array.isArray(links)) return "";
  return Object.entries(links).map(([platform, value]) => {
    const definition = platforms[platform];
    const url = safeSocialUrl(platform, value);
    if (!definition || !url) return "";
    const label = definition.label + " for " + profileName;
    return `<a class="${escapeHtml(className)}" data-platform="${platform}" href="${escapeHtml(url)}" target="_blank" rel="noopener noreferrer" data-outbound aria-label="${escapeHtml(label)}" title="${definition.label}">${socialIconSvg(platform)}${includeText ? `<span>${definition.label}</span><b aria-hidden="true">↗</b>` : ""}</a>`;
  }).join("");
}
